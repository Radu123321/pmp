
"""Exercitiul 3 - Restaurarea unei imagini binare folosind MRF si ICM."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import TypeAlias

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import networkx as nx
import numpy as np
from numpy.typing import NDArray
from pgmpy.factors.discrete import DiscreteFactor
from pgmpy.models import MarkovNetwork


BinaryImage: TypeAlias = NDArray[np.int8]
Pixel: TypeAlias = tuple[int, int]
Edge: TypeAlias = tuple[Pixel, Pixel]


@dataclass(frozen=True)
class Config:
    """Store the parameters used in the image restoration experiment.

    Attributes:
        size: Width and height of the binary image.
        seed: Random seed for reproducible noise generation.
        changed_pixels: Number of pixels inverted.
        lambdas: Fidelity parameters used in the experiment.
        output_dir: Directory where generated figures are saved.
    """

    size: int = 5
    seed: int = 42
    changed_pixels: int = 3
    lambdas: tuple[float, ...] = (0.3, 1.0, 3.0)
    output_dir: Path = Path("../rezultate_ex3")


# ---------------------------------------------------------
# a) Create the original binary image
# ---------------------------------------------------------

def make_original(size: int = 5) -> BinaryImage:
    """Create a 5x5 binary image with a centered white square.

    Args:
        size: Side length of the image. Must be 5.

    Returns:
        A binary NumPy array containing zeroes and ones.

    Raises:
        ValueError: If the requested size is not 5.
    """
    if size != 5:
        raise ValueError("The image size must be 5x5.")

    original = np.zeros((size, size), dtype=np.int8)
    original[1:4, 1:4] = 1

    return original


# ---------------------------------------------------------
# b) Generate reproducible noise
# ---------------------------------------------------------

def add_noise(
    original: BinaryImage,
    count: int,
    seed: int,
) -> tuple[BinaryImage, tuple[Pixel, ...]]:
    """Invert randomly selected pixels without modifying the original.

    Args:
        original: Original binary image.
        count: Number of distinct pixels to invert.
        seed: Random seed used for reproducibility.

    Returns:
        A tuple containing the noisy image and modified positions.

    Raises:
        ValueError: If count is outside the valid pixel range.
    """
    if not 0 <= count <= original.size:
        raise ValueError("Invalid number of pixels to modify.")

    rng = np.random.default_rng(seed)

    indices = rng.choice(
        original.size,
        size=count,
        replace=False,
    )

    observed = original.copy()
    observed.flat[indices] = 1 - observed.flat[indices]

    positions = tuple(
        (
            int(index // original.shape[1]),
            int(index % original.shape[1]),
        )
        for index in indices
    )

    return observed, positions


# ---------------------------------------------------------
# c) Build the Markov Random Field graph
# ---------------------------------------------------------

def grid_edges(size: int) -> list[Edge]:
    """Generate undirected edges for a four-neighbor pixel grid.

    Each pixel is connected only to its horizontal and vertical
    neighbors. Every undirected edge is included exactly once.

    Args:
        size: Side length of the square grid.

    Returns:
        A list of edges between neighboring pixels.
    """
    edges: list[Edge] = []

    for row in range(size):
        for col in range(size):

            if row + 1 < size:
                edges.append(
                    ((row, col), (row + 1, col))
                )

            if col + 1 < size:
                edges.append(
                    ((row, col), (row, col + 1))
                )

    return edges


def make_graph(
    size: int,
    edges: list[Edge],
) -> nx.Graph:
    """Construct the undirected pixel-neighborhood graph.

    Args:
        size: Side length of the image.
        edges: Pixel connections generated by grid_edges().

    Returns:
        A NetworkX graph representing the MRF structure.
    """
    graph = nx.Graph()

    graph.add_nodes_from(
        (row, col)
        for row in range(size)
        for col in range(size)
    )

    graph.add_edges_from(edges)

    return graph


def pixel_name(pixel: Pixel) -> str:
    """Convert pixel coordinates into a pgmpy variable name."""
    return f"X_{pixel[0]}_{pixel[1]}"


def build_pgmpy_mrf(
    observed: BinaryImage,
    edges: list[Edge],
    lam: float,
) -> MarkovNetwork:
    """Construct a Markov network with unary and pairwise factors.

    Unary potentials:
        phi_i(x_i) = exp(-lambda * (x_i - y_i)^2)

    Pairwise potentials:
        phi_ij(x_i, x_j) = exp(-(x_i - x_j)^2)

    Args:
        observed: Noisy binary image y.
        edges: Neighboring pixel pairs.
        lam: Positive observation fidelity parameter.

    Returns:
        A pgmpy MarkovNetwork with 25 unary factors
        and 40 pairwise factors for a 5x5 grid.

    Raises:
        ValueError: If lambda is not strictly positive.
    """
    if lam <= 0:
        raise ValueError("Lambda must be positive.")

    model = MarkovNetwork()

    height, width = observed.shape

    model.add_nodes_from(
        pixel_name((row, col))
        for row in range(height)
        for col in range(width)
    )

    model.add_edges_from(
        (pixel_name(first), pixel_name(second))
        for first, second in edges
    )

    # Unary factors
    for row in range(height):
        for col in range(width):
            observed_value = int(observed[row, col])

            potentials = [
                np.exp(-lam * (state - observed_value) ** 2)
                for state in (0, 1)
            ]

            factor = DiscreteFactor(
                variables=[pixel_name((row, col))],
                cardinality=[2],
                values=potentials,
            )

            model.add_factors(factor)

    # Pairwise factors
    pairwise_potential = np.array(
        [
            [1.0, np.exp(-1.0)],
            [np.exp(-1.0), 1.0],
        ]
    )

    for first, second in edges:
        factor = DiscreteFactor(
            variables=[
                pixel_name(first),
                pixel_name(second),
            ],
            cardinality=[2, 2],
            values=pairwise_potential.copy(),
        )

        model.add_factors(factor)

    model.check_model()

    return model


# ---------------------------------------------------------
# d) Calculate the energy and restore the image using ICM
# ---------------------------------------------------------

def calculate_energy(
    candidate: BinaryImage,
    observed: BinaryImage,
    edges: list[Edge],
    lam: float,
) -> float:
    """Calculate the total energy of a candidate reconstruction.

    Energy:
        E(x; y) = lambda * sum((x_i - y_i)^2)
                + sum((x_i - x_j)^2)

    Args:
        candidate: Candidate reconstructed image x.
        observed: Noisy image y.
        edges: Neighboring pixel pairs.
        lam: Fidelity parameter.

    Returns:
        The total energy of the candidate configuration.
    """
    difference = (
        candidate.astype(int) - observed.astype(int)
    )

    fidelity = lam * float(
        np.sum(difference ** 2)
    )

    smoothness = sum(
        (int(candidate[first]) - int(candidate[second])) ** 2
        for first, second in edges
    )

    return fidelity + smoothness


def calculate_local_energy(
    candidate: BinaryImage,
    observed: BinaryImage,
    graph: nx.Graph,
    pixel: Pixel,
    lam: float,
    state: int,
) -> float:
    """Calculate energy terms affected by one pixel state.

    Args:
        candidate: Current reconstructed image.
        observed: Original noisy observation.
        graph: Pixel neighborhood graph.
        pixel: Coordinates of the pixel being evaluated.
        lam: Fidelity parameter.
        state: Candidate binary value, either 0 or 1.

    Returns:
        Local energy associated with the selected pixel.
    """
    fidelity = lam * (
        state - int(observed[pixel])
    ) ** 2

    smoothness = sum(
        (state - int(candidate[neighbor])) ** 2
        for neighbor in graph.neighbors(pixel)
    )

    return float(fidelity + smoothness)


def restore_using_icm(
    observed: BinaryImage,
    graph: nx.Graph,
    lam: float,
    max_iterations: int = 100,
) -> tuple[BinaryImage, int]:
    """Restore a binary image using Iterated Conditional Modes.

    The algorithm starts from the observed image and evaluates
    both possible values for every pixel.

    A pixel is changed only if doing so strictly reduces
    its local energy.

    ICM is a local optimization algorithm and does not guarantee
    finding the global MAP configuration.

    Args:
        observed: Noisy binary image.
        graph: Pixel neighborhood graph.
        lam: Positive fidelity parameter.
        max_iterations: Maximum number of full grid sweeps.

    Returns:
        The reconstructed image and number of completed sweeps.

    Raises:
        ValueError: If lambda is not strictly positive.
    """
    if lam <= 0:
        raise ValueError("Lambda must be positive.")

    result = observed.copy()

    for iteration in range(1, max_iterations + 1):
        changed = False

        for pixel in graph.nodes:
            current_state = int(result[pixel])
            alternate_state = 1 - current_state

            current_energy = calculate_local_energy(
                result,
                observed,
                graph,
                pixel,
                lam,
                current_state,
            )

            alternate_energy = calculate_local_energy(
                result,
                observed,
                graph,
                pixel,
                lam,
                alternate_state,
            )

            if alternate_energy < current_energy - 1e-12:
                result[pixel] = alternate_state
                changed = True

        if not changed:
            return result, iteration

    return result, max_iterations


# ---------------------------------------------------------
# e) Compare reconstruction results
# ---------------------------------------------------------

def count_pixel_errors(
    reconstructed: BinaryImage,
    original: BinaryImage,
) -> int:
    """Count pixels that differ from the original image.

    Args:
        reconstructed: Restored image.
        original: Ground-truth binary image.

    Returns:
        Number of incorrectly reconstructed pixels.
    """
    return int(
        np.count_nonzero(reconstructed != original)
    )


def save_graph(
    graph: nx.Graph,
    destination: Path,
) -> None:
    """Save the Markov Random Field graph as a PNG image."""
    figure, axis = plt.subplots(figsize=(7, 6))

    positions = {
        (row, col): (col, -row)
        for row, col in graph.nodes
    }

    labels = {
        pixel: f"{pixel[0]},{pixel[1]}"
        for pixel in graph.nodes
    }

    nx.draw(
        graph,
        pos=positions,
        labels=labels,
        ax=axis,
        with_labels=True,
        node_color="#d8ebff",
        node_size=650,
        font_size=8,
        edge_color="#64748b",
    )

    axis.set_title("MRF 5x5 - 25 nodes, 40 edges")

    figure.tight_layout()
    figure.savefig(destination, dpi=180)
    plt.close(figure)


def save_comparison(
    images: list[tuple[str, BinaryImage]],
    destination: Path,
) -> None:
    """Save the original, noisy and reconstructed images.

    Args:
        images: List containing image titles and binary matrices.
        destination: Output PNG file path.
    """
    figure, axes = plt.subplots(
        1,
        len(images),
        figsize=(3.3 * len(images), 3.8),
    )

    for axis, (title, image) in zip(
        np.atleast_1d(axes),
        images,
    ):
        axis.imshow(
            image,
            cmap="gray",
            vmin=0,
            vmax=1,
            interpolation="nearest",
        )

        axis.set_title(title, fontsize=10)
        axis.set_xticks(range(image.shape[1]))
        axis.set_yticks(range(image.shape[0]))
        axis.grid(color="#aaaaaa", linewidth=0.5)

    figure.tight_layout()
    figure.savefig(destination, dpi=180)
    plt.close(figure)


# ---------------------------------------------------------
# Main
# ---------------------------------------------------------

def main() -> None:
    """Execute all exercise requirements from a) to e)."""
    config = Config()

    config.output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # a) Original image
    original = make_original(config.size)

    # b) Add random noise
    observed, modified_pixels = add_noise(
        original,
        config.changed_pixels,
        config.seed,
    )

    # c) Construct the MRF graph
    edges = grid_edges(config.size)
    graph = make_graph(config.size, edges)

    assert graph.number_of_nodes() == 25
    assert len(edges) == 40

    save_graph(
        graph,
        config.output_dir / "graf_mrf.png",
    )

    print("\na) Original image:")
    print(original)

    print("\nb) Observed noisy image:")
    print(observed)

    print("\nRandom seed:", config.seed)
    print("Modified pixel positions:", modified_pixels)

    print("\nc) MRF graph:")
    print("Nodes:", graph.number_of_nodes())
    print("Edges:", graph.number_of_edges())
    print("Unary factors: 25")
    print("Pairwise factors: 40")

    initial_errors = count_pixel_errors(
        observed,
        original,
    )

    print("\nInitial incorrect pixels:", initial_errors)

    images: list[tuple[str, BinaryImage]] = [
        ("Original", original),
        ("Observed (noisy)", observed),
    ]

    # d/e) Restore the image for different lambda values
    for lam in config.lambdas:
        model = build_pgmpy_mrf(
            observed,
            edges,
            lam,
        )

        assert len(model.get_factors()) == 65

        reconstructed, iterations = restore_using_icm(
            observed,
            graph,
            lam,
        )

        final_energy = calculate_energy(
            reconstructed,
            observed,
            edges,
            lam,
        )

        errors = count_pixel_errors(
            reconstructed,
            original,
        )

        print(f"\nLambda = {lam}")
        print(f"ICM iterations = {iterations}")
        print(f"Final energy = {final_energy:.4f}")
        print(f"Incorrect pixels = {errors}")
        print(reconstructed)

        images.append(
            (
                f"lambda={lam:g}\nerrors={errors}",
                reconstructed,
            )
        )

    save_comparison(
        images,
        config.output_dir / "comparatie_reconstructii.png",
    )

    print("\nGenerated images saved in:")
    print(config.output_dir.resolve())


if __name__ == "__main__":
    main()
